export function DotMatrixText({ text, variant }: DotMatrixTextProps) {
  return (
    <span className={`dot-matrix dot-matrix--${variant}`} aria-label={text}>
      {[...text].map((character, index) => {
        const rows = glyphs[character] ?? glyphs[character.toUpperCase()] ?? glyphs["0"];
        const columns = rows[0].length;
        return (
          <span
            className="dot-matrix__glyph"
            key={`${character}-${index}`}
            style={{ gridTemplateColumns: `repeat(${columns}, var(--dot-size))` }}
            aria-hidden="true"
          >
            {rows.flatMap((row, rowIndex) =>
              [...row].map((cell, columnIndex) => (
                <i className={cell === "1" ? "is-on" : "is-off"} key={`${rowIndex}-${columnIndex}`} />
              )),
            )}
          </span>
        );
      })}
    </span>
  );
}
